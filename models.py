import re
from typing import List, Optional, Dict, Any
from pydantic import BaseModel, Field


class SourceItem(BaseModel):
    """Represents a discovered web source and its extracted content."""
    title: str = Field(default="Untitled", description="Title of the source webpage or article")
    url: str = Field(..., description="Canonical URL of the source")
    snippet: str = Field(default="", description="Search snippet or initial preview")
    content: str = Field(default="", description="Extracted clean text content from the URL")
    is_scraped: bool = Field(default=False, description="Whether full content extraction succeeded")
    error: Optional[str] = Field(default=None, description="Error message if scraping failed")

    def to_display_snippet(self, max_length: int = 250) -> str:
        """Return a clean snippet for UI and prompt display."""
        text = self.content.strip() if (self.is_scraped and self.content.strip()) else self.snippet.strip()
        if len(text) > max_length:
            return text[:max_length] + "..."
        return text or "No preview available."


class ResearchReport(BaseModel):
    """Structured research report with verified sections."""
    topic: str = Field(..., description="The research topic")
    executive_summary: str = Field(..., description="High-level executive summary of the topic and research")
    introduction: str = Field(..., description="Contextual background and problem definition")
    key_findings: List[str] = Field(..., description="Key findings with thorough explanations (minimum 3)")
    detailed_analysis: str = Field(..., description="In-depth analysis distinguishing source-supported facts from synthesis")
    conclusion: str = Field(..., description="Concluding synthesis and forward-looking outlook")
    references: List[str] = Field(default_factory=list, description="List of actual source URLs cited in the research")

    def to_markdown(self) -> str:
        """Render the structured report as clean GitHub-style Markdown."""
        lines = []
        lines.append(f"# Research Report: {self.topic}\n")
        
        lines.append("## Executive Summary")
        lines.append(self.executive_summary.strip() + "\n")
        
        lines.append("## Introduction")
        lines.append(self.introduction.strip() + "\n")
        
        lines.append("## Key Findings")
        for i, finding in enumerate(self.key_findings, 1):
            clean_finding = finding.strip()
            # If the item doesn't already start with a bullet or number, add number
            if not re.match(r"^(\d+\.|\-|\*)\s", clean_finding):
                lines.append(f"{i}. {clean_finding}")
            else:
                lines.append(clean_finding)
        lines.append("")
        
        lines.append("## Detailed Analysis")
        lines.append(self.detailed_analysis.strip() + "\n")
        
        lines.append("## Conclusion")
        lines.append(self.conclusion.strip() + "\n")
        
        lines.append("## References")
        if self.references:
            # Deduplicate references while preserving order
            seen_refs = set()
            for ref in self.references:
                clean_ref = ref.strip()
                if clean_ref and clean_ref not in seen_refs:
                    seen_refs.add(clean_ref)
                    lines.append(f"- <{clean_ref}>")
        else:
            lines.append("- *No external source references available.*")
        
        return "\n".join(lines)


class CriticEvaluation(BaseModel):
    """Structured evaluation generated by the Critic Agent."""
    score: float = Field(..., ge=1.0, le=10.0, description="Overall quality score from 1.0 to 10.0")
    strengths: List[str] = Field(default_factory=list, description="Identified strengths of the report")
    weak_explanations: List[str] = Field(default_factory=list, description="Weak, shallow, or unclear explanations")
    missing_information: List[str] = Field(default_factory=list, description="Important aspects of the topic that were omitted")
    unsupported_claims: List[str] = Field(default_factory=list, description="Claims made without evidential source support")
    actionable_recommendations: List[str] = Field(default_factory=list, description="Concrete suggestions for refinement")
    needs_refinement: bool = Field(default=False, description="True if report requires revision, False if acceptable")
    verdict: str = Field(..., description="One-line summary verdict on the report")

    def to_markdown(self) -> str:
        """Render the structured evaluation as clean GitHub-style Markdown."""
        lines = []
        status_label = "[Revision Needed]" if self.needs_refinement else "[Approved]"
        lines.append(f"### Evaluation Score: **{self.score:.1f} / 10** ({status_label})\n")
        lines.append(f"**Verdict:** {self.verdict.strip()}\n")
        
        if self.strengths:
            lines.append("#### Strengths")
            for s in self.strengths:
                lines.append(f"- {s.strip()}")
            lines.append("")

        if self.missing_information:
            lines.append("#### Missing Information Identified")
            for m in self.missing_information:
                lines.append(f"- {m.strip()}")
            lines.append("")

        if self.weak_explanations:
            lines.append("#### Weak or Shallow Explanations")
            for w in self.weak_explanations:
                lines.append(f"- {w.strip()}")
            lines.append("")

        if self.unsupported_claims:
            lines.append("#### Unsupported Claims Checked")
            for u in self.unsupported_claims:
                lines.append(f"- {u.strip()}")
            lines.append("")

        if self.actionable_recommendations:
            lines.append("#### Actionable Refinement Suggestions")
            for a in self.actionable_recommendations:
                lines.append(f"- {a.strip()}")
            lines.append("")

        return "\n".join(lines)


class PipelineResult(BaseModel):
    """Complete container for research execution results."""
    topic: str
    sources: List[SourceItem] = Field(default_factory=list)
    report: ResearchReport
    critic_evaluations: List[CriticEvaluation] = Field(default_factory=list)
    final_critic_evaluation: Optional[CriticEvaluation] = None
    refinement_attempts: int = 0
    raw_markdown_report: str = ""

    def to_state_dict(self) -> Dict[str, Any]:
        """Convert result into standard dictionary format compatible with UI and legacy code."""
        report_md = self.report.to_markdown() if self.report else self.raw_markdown_report
        final_critic_md = self.final_critic_evaluation.to_markdown() if self.final_critic_evaluation else ""

        # Format search and reader summaries
        search_summaries = []
        reader_summaries = []
        for s in self.sources:
            search_summaries.append(f"Title: {s.title}\nURL: {s.url}\nSnippet: {s.snippet}\n")
            status = "Scraped Successfully" if s.is_scraped else f"Snippet Only ({s.error or 'Failed'})"
            content_preview = s.content[:500] if s.is_scraped else s.snippet
            reader_summaries.append(f"Source: {s.title}\nURL: {s.url}\nStatus: {status}\nContent:\n{content_preview}\n")

        return {
            "topic": self.topic,
            "sources": self.sources,
            "sources_data": [s.model_dump() for s in self.sources],
            "search": "\n----\n".join(search_summaries),
            "search_results": "\n----\n".join(search_summaries),
            "reader": "\n----\n".join(reader_summaries),
            "scraped_content": "\n----\n".join(reader_summaries),
            "writer": report_md,
            "report": report_md,
            "report_model": self.report,
            "critic": final_critic_md,
            "feedback": final_critic_md,
            "critic_model": self.final_critic_evaluation,
            "evaluations": [ev.model_dump() if hasattr(ev, "model_dump") else ev for ev in self.critic_evaluations],
            "evaluation_models": self.critic_evaluations,
            "refinement_attempts": self.refinement_attempts,
        }
